CREATE TABLE FOROHUB_USUARIOS (
 ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 NOMBRE VARCHAR2(60 CHAR) NOT NULL,
 EMAIL VARCHAR2(120 CHAR) NOT NULL UNIQUE,
 PASSWORD_HASH VARCHAR2(120 CHAR) NOT NULL,
 ROL VARCHAR2(12 CHAR) NOT NULL,
 BIO VARCHAR2(250 CHAR)
);
CREATE TABLE FOROHUB_TEMAS (
 ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 TITULO VARCHAR2(100 CHAR) NOT NULL,
 CONTENIDO VARCHAR2(3000 CHAR) NOT NULL,
 CATEGORIA VARCHAR2(30 CHAR) NOT NULL,
 AUTOR_ID NUMBER(19) NOT NULL,
 AUTOR VARCHAR2(60 CHAR) NOT NULL,
 FECHA TIMESTAMP(6) WITH TIME ZONE,
 OCULTO NUMBER(1) DEFAULT 0,
 DESTACADO NUMBER(1) DEFAULT 0,
 VISTAS NUMBER(10) DEFAULT 0
);
CREATE TABLE FOROHUB_COMENTARIOS (
 ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 TEMA_ID NUMBER(19) NOT NULL,
 AUTOR_ID NUMBER(19) NOT NULL,
 AUTOR VARCHAR2(60 CHAR) NOT NULL,
 CONTENIDO VARCHAR2(1000 CHAR) NOT NULL,
 FECHA TIMESTAMP(6) WITH TIME ZONE,
 OCULTO NUMBER(1) DEFAULT 0
);
CREATE TABLE FOROHUB_MODERACION (
 ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 TIPO VARCHAR2(30 CHAR) NOT NULL,
 RECURSO_ID NUMBER(19) NOT NULL,
 ACCION VARCHAR2(20 CHAR) NOT NULL,
 ADMINISTRADOR VARCHAR2(60 CHAR) NOT NULL,
 FECHA TIMESTAMP(6) WITH TIME ZONE
);
-- La PK y los campos siguen las entidades JPA. DDL ilustrativo sujeto a dialecto Oracle.
